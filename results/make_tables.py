"""Rebuilds the paper's Tables 13 and 14 from the per-frame results in this folder.

    python3 results/make_tables.py            -> prints the tables and writes results/TABLES.md

Each cell is direction accuracy (%) with false commands (%) in brackets: a false command is a
LEFT or RIGHT output for a NEUTRAL gesture, as a share of the NEUTRAL frames. LEFT/RIGHT accuracy
is the accuracy on the LEFT and RIGHT frames in clear air; "mirrored" is the accuracy on the
mirrored real frames (LEFT and RIGHT swapped) in clear air. Only pandas is needed.
"""
import os

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
LR = ('LEFT', 'RIGHT')
HELDOUT = (1, 3, 11, 14)
NAMES = {'alg1_rgb': ('Algorithm 1', 'RGB'), 'alg1_depth': ('Algorithm 1', 'Depth'),
         'alg1_fused': ('Algorithm 1, fused pose', 'RGB-D'),
         'yolov11_ltotal_synthetic': ('YOLOv11-L_total', 'RGB-D, synthetic-trained'),
         'yolov11_ltotal_real': ('YOLOv11-L_total', 'RGB-D, trained on 5 real subject IDs')}


def pct(x):
    """Percent rounded half up (as in the paper), e.g. 92.5 -> 93."""
    return f'{int(x + 0.5 + 1e-9)}'


def cell(d, truth):
    acc = (d.pred == d[truth]).mean() * 100
    n = d[d[truth] == 'NEUTRAL']
    fc = n.pred.isin(LR).mean() * 100
    return f'{pct(acc)} ({pct(fc)})'


def lr_acc(d, truth):
    q = d[d[truth].isin(LR)]
    return pct((q.pred == q[truth]).mean() * 100)


def synthetic():
    d = pd.read_csv(f'{HERE}/synthetic_test_set/frames.csv')
    conds = [('clear', 'Clear'), ('particle', 'Particle fog'), ('phys50', 'V 50 m'), ('phys20', 'V 20 m'),
             ('phys10', 'V 10 m'), ('phys5', 'V 5 m')]
    rows = ['| Pipeline | Input | ' + ' | '.join(c for _, c in conds) + ' | LEFT/RIGHT acc. |',
            '|---|---|' + '---|' * (len(conds) + 1)]
    for p in ('alg1_rgb', 'alg1_depth', 'alg1_fused', 'yolov11_ltotal_synthetic'):
        q = d[d.pipeline == p]
        cells = [cell(q[q.cond == c], 'truth') for c, _ in conds]
        rows.append(f'| {NAMES[p][0]} | {NAMES[p][1]} | ' + ' | '.join(cells) +
                    f' | {lr_acc(q[q.cond == "clear"], "truth")} |')
    n = {c: int((d[d.pipeline == "alg1_rgb"].cond == c).sum()) for c, _ in conds}
    ms = d.groupby('pipeline').proc_ms.median().round().astype(int).to_dict()
    return (['## Table 13: synthetic test set (City, Forest, Wall; never used for training)', ''] + rows +
            ['', f'Frames per condition: {n}. Median processing time per frame (ms): {ms}.', ''])


def real():
    d = pd.read_csv(f'{HERE}/uav_gesture/frames.csv.gz')
    m = pd.read_csv(f'{HERE}/uav_gesture/frames_mirrored.csv.gz')
    conds = [('clear', 'Clear'), ('phys50', 'V 50 m'), ('phys20', 'V 20 m'), ('phys10', 'V 10 m'), ('phys5', 'V 5 m')]
    out = ['## Table 14: real people (UAV-GESTURE), depth estimated from RGB', '']
    for title, subj, pipes in (
            ('All 11 subject IDs', None, ('alg1_rgb', 'alg1_depth', 'alg1_fused', 'yolov11_ltotal_synthetic')),
            ('Four held-out subject IDs (S1, S3, S11, S14)', HELDOUT,
             ('alg1_rgb', 'alg1_depth', 'alg1_fused', 'yolov11_ltotal_synthetic', 'yolov11_ltotal_real'))):
        a, b = (d, m) if subj is None else (d[d.subject.isin(subj)], m[m.subject.isin(subj)])
        c = a[(a.pipeline == 'alg1_rgb') & (a.cond == 'clear')].label.value_counts().to_dict()
        out += [f'**{title}**: {sum(c.values())} frames {c}', '',
                '| Pipeline | Input | ' + ' | '.join(x for _, x in conds) + ' | LEFT/RIGHT acc. | Mirrored |',
                '|---|---|' + '---|' * (len(conds) + 2)]
        for p in pipes:
            q, qm = a[a.pipeline == p], b[b.pipeline == p]
            cells = [cell(q[q.cond == k], 'label') for k, _ in conds]
            qc, qmc = q[q.cond == 'clear'], qm[qm.cond == 'clear']
            mir = pct((qmc.pred == qmc.label).mean() * 100)
            out.append(f'| {NAMES[p][0]} | {NAMES[p][1]} | ' + ' | '.join(cells) +
                       f' | {lr_acc(qc, "label")} | {mir} |')
        out.append('')
    return out


if __name__ == '__main__':
    lines = ['# Tables of the extended evaluation (paper Section 7)', '',
             'Generated by `results/make_tables.py` from the per-frame results in this folder. '
             'Cells: direction accuracy % (false commands %).', ''] + synthetic() + real()
    open(f'{HERE}/TABLES.md', 'w').write('\n'.join(lines))
    print('\n'.join(lines))
