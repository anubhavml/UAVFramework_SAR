def ground(rgb, size=200):
    return f"""    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision">
          <geometry><plane><normal>0 0 1</normal><size>{size} {size}</size></plane></geometry>
        </collision>
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>{size} {size}</size></plane></geometry>
          <material><ambient>{rgb} 1</ambient><diffuse>{rgb} 1</diffuse><specular>0.1 0.1 0.1 1</specular></material>
        </visual>
      </link>
    </model>
"""


SHIFT_X = 0.0   # per-world X offset applied to every placed object (set in __main__)


def include(uri, name, x, y, yaw=0.0, z=0.0, scale=None):
    x = round(x + SHIFT_X, 3)
    sc = f'\n      <scale>{scale} {scale} {scale}</scale>' if scale else ''
    return f"""    <include>
      <uri>model://{uri}</uri>
      <name>{name}</name>
      <pose>{x} {y} {z} 0 0 {yaw}</pose>{sc}
    </include>
"""


def box(name, x, y, sx, sy, sz, rgb, yaw=0.0):
    x = round(x + SHIFT_X, 3)
    return f"""    <model name="{name}">
      <static>true</static>
      <pose>{x} {y} {sz / 2} 0 0 {yaw}</pose>
      <link name="link">
        <collision name="collision"><geometry><box><size>{sx} {sy} {sz}</size></box></geometry></collision>
        <visual name="visual">
          <geometry><box><size>{sx} {sy} {sz}</size></box></geometry>
          <material><ambient>{rgb} 1</ambient><diffuse>{rgb} 1</diffuse><specular>0.05 0.05 0.05 1</specular></material>
        </visual>
      </link>
    </model>
"""


def fog(cx, cy, extent, rate):
    """Ground fog: box particle emitter (Fuel 'Fog Generator' textures), rising slowly.

    `rate` sets the steady-state density; it is tuned per world so that, as in the paper's fog
    test, the person is detected at 3.5 m and lost by 7.5-10 m (wall shading makes its fog
    look thinner, so it needs more particles)."""
    cx = round(cx + SHIFT_X, 3)
    return f"""    <model name="fog_generator">
      <static>true</static>
      <pose>{cx} {cy} 0 0 -1.5707 0</pose>
      <link name="fog_link">
        <particle_emitter name="fog_emitter" type="box">
          <emitting>true</emitting>
          <size>4 {extent} {extent}</size>
          <particle_size>3 3 3</particle_size>
          <lifetime>20</lifetime>
          <min_velocity>0.05</min_velocity>
          <max_velocity>0.2</max_velocity>
          <scale_rate>0.4</scale_rate>
          <rate>{rate}</rate>
          <particle_scatter_ratio>0.35</particle_scatter_ratio>
          <material>
            <diffuse>0.75 0.75 0.75</diffuse>
            <specular>1.0 1.0 1.0</specular>
            <pbr><metal><albedo_map>model://fog_generator/materials/textures/fog.png</albedo_map></metal></pbr>
          </material>
        </particle_emitter>
      </link>
    </model>
"""


FOG_PLUGIN = """
    <plugin name="gz::sim::systems::ParticleEmitter" filename="gz-sim-particle-emitter-system"/>"""


def forest():
    # Oaks and pines surrounding the human (Fig. 4 / Envs screenshot 13-43-19)
    body = ground('0.85 0.85 0.85')
    oaks = [(5.5, 8.0, 0.3), (8.0, 4.6, 1.9), (12.5, 1.2, 0.8), (11.2, -4.2, 2.6),
            (13.8, -7.2, 4.1), (9.6, -8.8, 1.2), (6.0, -11.0, 5.3), (15.5, 5.5, 3.3)]
    pines = [(5.0, 11.0), (9.2, 7.2), (13.0, 3.8), (7.4, -1.9), (14.5, -2.2), (16.0, -9.5)]
    for i, (x, y, yaw) in enumerate(oaks):
        body += include('oak_tree', f'oak_{i}', x, y, yaw)
    for i, (x, y) in enumerate(pines):
        body += include('pine_tree', f'pine_{i}', x, y)
    body += include('sar_human_right', 'sar_human', 9.8, 0.4, PI)
    return body, dict(bg='0.86 0.86 0.86', sun_dir='0.35 0.55 -0.76', gui_cam='-6 3 5 0 0.35 -0.2'), (9, 0, 8)


def city():
    # Collapsed buildings, school, playground, trees (Fig. 5 / Envs screenshots 13-45-58, 19-1x)
    # Fuel meshes are in inches: school 33 x 17.5 x 14 m, playground 11.5 x 6.7 m,
    # collapsed industrial building ~23 m wide x 24 m tall.
    body = ground('0.86 0.86 0.86', size=300)
    body += include('collapsed_industrial', 'collapsed_building_0', 46.0, 24.0, 0.35)
    body += include('collapsed_industrial', 'collapsed_building_1', 50.0, 1.0, -0.15)
    body += include('collapsed_industrial', 'collapsed_building_2', 45.0, -26.0, 1.25)
    # school runs along the right-hand side (x -19.5..13.5), facade (hedge, door) facing +Y
    body += include('school', 'school', -3.0, -11.6, 0.0)
    body += include('playground', 'playground', 11.0, 8.0, 0.25)
    body += include('oak_tree', 'oak_0', 16.5, -1.5, 1.0)
    body += include('pine_tree', 'pine_0', 22.0, 15.0)
    body += include('sar_human_right', 'sar_human', 13.5, -1.2, PI)
    return body, dict(bg='0.9 0.9 0.9', sun_dir='0.35 -0.45 -0.82', gui_cam='-8 3 7 0 0.3 -0.1'), (11, 0, 8)


def wall():
    # Enclosed space with a high black wall (Fig. 6 / Envs screenshots 13-44-57, 19-05-07)
    dark, black, light = '0.38 0.38 0.38', '0.12 0.12 0.12', '0.72 0.72 0.72'
    body = ground(dark, size=60)
    body += box('wall_back', 12.0, 0.0, 0.4, 30.0, 8.0, black)
    body += box('wall_left', -3.0, 15.0, 30.0, 0.4, 8.0, black)
    body += box('wall_right', -3.0, -15.0, 30.0, 0.4, 8.0, black)
    body += box('wall_rear', -18.0, 0.0, 0.4, 30.0, 8.0, black)
    body += box('wall_partition', 3.5, 5.5, 9.0, 0.5, 6.0, light, 0.12)
    body += include('sar_human_right', 'sar_human', 11.3, -1.2, PI)
    return body, dict(bg='0.35 0.35 0.35', sun_dir='0.25 -0.45 -0.86', gui_cam='-5 2 4 0 0.25 -0.15'), (6, 0, 14)


if __name__ == '__main__':
    os.makedirs(WORLDS_DIR, exist_ok=True)
    # shifts put the human at ~7.8 m (forest), ~7.5 m (city), ~7.8 m (wall) from the spawn point
    for name, fn, shift in (('forest', forest, -2.0), ('city', city, -6.0), ('wall', wall, -3.5)):
        SHIFT_X = shift
        body, hdr, (fx, fy, frate) = fn()
        for fogged in (False, True):
            wname = f'{name}_fog' if fogged else name
            sdf = HEADER.format(name=wname, extra_plugins=FOG_PLUGIN if fogged else '', **hdr)
            sdf += body + (fog(fx, fy, 26, frate) if fogged else '') + FOOTER
            path = os.path.join(WORLDS_DIR, f'{wname}.sdf')
            with open(path, 'w') as fh:
                fh.write(sdf)
            print('wrote', path)
